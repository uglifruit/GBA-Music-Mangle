#!/usr/bin/env python3
"""Author a small native-layout MusyX PCM fixture. No game assets or original driver code.
Usage: make_demo.py OUT.gba [OUT.h]
"""
import pathlib
import struct
import sys

def make_demo():
    data=bytearray(4096)
    def put(a,fmt,*values):struct.pack_into('<'+fmt,data,a,*values)
    root=0x100
    def rel(field,target,anchor=root):put(field,'I',target-anchor)
    data[0xA0:0xAC]=b'MUSYXPOCDEMO';data[0xAC:0xB0]=b'MSY0';data[0xB2]=0x96
    rel(root,0x140);rel(root+4,0x180);rel(root+24,0x500);rel(root+28,0x200)
    rel(0x140,0x148);rel(0x144,0x160)
    data[0x148:0x14D]=bytes([255,0,0,0,0])
    data[0x160:0x164]=bytes([255,0,0,0])
    put(0x164,'BBHI',15,0,1,0) # STARTSAMPLE 1
    put(0x16C,'BBH',4,0,65535) # WAIT_TICKS forever, until note-off
    data[0x170]=0
    rel(0x200,0x208);rel(0x204,0x328)
    put(0x208,'IiHHI',256,-1,16384,60,0)
    put(0x328,'IiHHI',256,0,16384,60,0)
    for i in range(256):data[0x338+i]=(16+(i%32)*7-128)&255
    put(0x500,'I',1);rel(0x504,0x600)
    put(0x610,'HBB',1,0,8);put(0x810,'HBB',1,0,8)
    song=0xA10;rel(song,0xA20,song);rel(song+4,0xA70,song);put(song+8,'H',120)
    rel(0xA20,0xA90,song);rel(0xA20+16*4,0xAD0,song)
    for i,a in enumerate([0xB10,0xB30,0xB50]):rel(0xA70+4*i,a,song)
    put(0xA90,'iiiiiiii',0,0,96,1,96,-2,0,0)
    put(0xAD0,'iiiiii',0,2,192,-1,0,0)
    for a,notes in [(0xB10,(60,64)),(0xB30,(67,71))]:
        put(a,'HBBBBH',0,100,notes[0]|128,0,0,48)
        put(a+8,'HBBH',0,90,notes[1],48)
        put(a+14,'I',0xFFFFFFFF)
    put(0xB50,'HHI',96,150,0xFFFFFFFF)
    return bytes(data)

if __name__=='__main__':
    data=make_demo();pathlib.Path(sys.argv[1]).write_bytes(data)
    if len(sys.argv)>2:
        entries=[f'    [0x{i:03X}] = 0x{v:02X},' for i,v in enumerate(data) if v]
        pathlib.Path(sys.argv[2]).write_text('// Authored native-format test tune; generated by tests/make_demo.py.\nstatic const uint8_t ms_demo_rom[4096] = {\n'+'\n'.join(entries)+'\n};\n')
    print('root 0x08000100, song index 0; authored PCM demo')
